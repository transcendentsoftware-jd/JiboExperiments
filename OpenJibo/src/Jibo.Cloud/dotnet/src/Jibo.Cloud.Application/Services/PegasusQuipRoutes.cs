    private static readonly IReadOnlyDictionary<string, Route> ByIntent =
        Routes.ToDictionary(route => route.Intent, StringComparer.Ordinal);

    private static readonly IReadOnlyDictionary<string, Route> ByMimId =
        Routes.ToDictionary(route => route.MimId, StringComparer.OrdinalIgnoreCase);

    private static readonly ILookup<string, string> SpokenIntents =
        Routes.SelectMany(route => route.Phrases.Select(phrase => (Phrase: phrase, route.Intent)))
            .ToLookup(entry => entry.Phrase, entry => entry.Intent, StringComparer.Ordinal);

    private static readonly string[] VisualRequests = SpokenIntents
        .Select(group => group.Key)
        .Where(phrase => phrase.StartsWith("show me ", StringComparison.Ordinal))
        .ToArray();

    internal static bool LooksLikeIncompleteVisualRequest(string transcript)
    {
        var start = transcript.LastIndexOf("show me ", StringComparison.Ordinal);
        if (start < 0 || (start > 0 && transcript[start - 1] != ' ')) return false;

        var request = transcript[start..];
        if (request.Length - request.LastIndexOf(' ') < 4 || SpokenIntents.Contains(request))
            return false;

        return VisualRequests.Any(phrase => phrase.StartsWith(request, StringComparison.Ordinal));
    }

    internal static string? Resolve(
        string phrase, string? clientIntent, IReadOnlyDictionary<string, string> entities)
    {
        if (string.Equals(clientIntent, "requestMakeSound", StringComparison.OrdinalIgnoreCase) &&
            !entities.ContainsKey("Animal") && entities.TryGetValue("AnimalSound", out var animalSound))
        {
            if (string.Equals(animalSound, "Cat", StringComparison.OrdinalIgnoreCase)) return "robot_make_cat_sound";
            if (string.Equals(animalSound, "Dog", StringComparison.OrdinalIgnoreCase)) return "robot_make_dog_sound";
        }

        phrase = NormalizeSpokenPhrase(phrase);
        const string trailingReaction = " oh wow";
        if (phrase.EndsWith(trailingReaction, StringComparison.Ordinal)) phrase = phrase[..^trailingReaction.Length];

        var spokenIntent = SpokenIntents[phrase].FirstOrDefault();
        if (spokenIntent is not null) return spokenIntent;

        // The generic emoji route has an entity key but no value, so it only matches
        // a request that did not name a particular emoji.
        return Routes.FirstOrDefault(route =>
            string.Equals(route.ClientIntent, clientIntent, StringComparison.OrdinalIgnoreCase) &&
            (route.Entity is null ||
             string.Equals(entities.GetValueOrDefault(route.Entity), route.Value, StringComparison.OrdinalIgnoreCase) ||
             route.AlternateValues?.Contains(entities.GetValueOrDefault(route.Entity), StringComparer.OrdinalIgnoreCase) == true) &&
            (route.AdditionalEntity is not { } required ||
             string.Equals(entities.GetValueOrDefault(required.Entity), required.Value, StringComparison.OrdinalIgnoreCase)))
            ?.Intent;
    }

    internal static string? TryRecoverFromDisfluentSpeech(string phrase, string sourceTranscript)
    {
        if (sourceTranscript.IndexOfAny(['"', '“', '”']) >= 0) return null;

        // Try the longest command first, with at most ten trailing words.
        const int maxTrailingWords = 10;
        phrase = SkipLeadingDisfluencies(NormalizeSpokenPhrase(phrase), sourceTranscript);
        var boundary = phrase.Length;
        for (var trailingWords = 0; trailingWords <= maxTrailingWords && boundary > 0; trailingWords++)
        {
            var request = phrase[..boundary];
            if (request.AsSpan().Count(' ') < 2) return null;

            var intents = SpokenIntents[request];
            if (!intents.Any() && CollapseImmediateRepeats(request) is { } withoutRepeats)
                intents = SpokenIntents[withoutRepeats];

            if (intents.Any())
            {
                if (trailingWords > 0 && !IsTrailingConversation(phrase[(boundary + 1)..])) return null;

                var distinctIntents = intents.Distinct(StringComparer.Ordinal).Take(2).ToArray();
                return distinctIntents.Length == 1 ? distinctIntents[0] : null;
            }

            boundary = phrase.LastIndexOf(' ', boundary - 1);
        }

        return null;
    }

    private static string SkipLeadingDisfluencies(string phrase, string sourceTranscript)
    {
        for (var i = 0; i < 3; i++)
        {
            var space = phrase.IndexOf(' ');
            if (space < 0 || phrase[..space] is not ("oh" or "uh" or "um" or "er" or "hmm")) break;
            phrase = phrase[(space + 1)..];
        }

        const string interruptedSpeech = "i hear a ";
        const string restartedFalseStart = "i don't i don't ";
        if (phrase.StartsWith(interruptedSpeech, StringComparison.Ordinal))
            return phrase[interruptedSpeech.Length..];
        if (phrase.StartsWith(restartedFalseStart, StringComparison.Ordinal))
        {
            // Command normalization already removes hesitation words like "oh".
            var opening = TranscriptTextNormalizer.StripLeadingWakePhrase(sourceTranscript).Split(' ', 2)[0];
            if (opening is "oh" or "uh" or "um" or "er" or "hmm")
                return phrase[restartedFalseStart.Length..];
        }

        return phrase;
    }

    private static string? CollapseImmediateRepeats(string request)
    {
        var words = request.Split(' ');
        var start = words is [var first, var second, var third, var fourth, ..] &&
                    first == third && second == fourth ? 2 : 0;
        var count = 0;
        for (var i = start; i < words.Length; i++)
        {
            if (count == 0 || words[i] != words[count - 1])
                words[count++] = words[i];
        }

        return count >= 3 && count < words.Length ? string.Join(' ', words, 0, count) : null;
    }

    private static bool IsTrailingConversation(string tail)
    {
        if (tail is "uh" or "um" or "er" or "hmm" or "yeah" or "okay" or "ok" or
            "probably did" or "i think" or "i know" or "you know")
            return true;

        // A joining word alone is insufficient. Match a conversational clause
        // with a subject and a verb before treating it as background speech.
        var words = tail.Split(' ');
        if (words is ["and" or "in", "i" or "we" or "he" or "she" or "they" or "it",
            "go" or "went" or "did" or "said" or "know" or "think"] or
            ["and" or "in", "i" or "we" or "he" or "she" or "they", "go" or "went", "to", "the",
                "circus" or "zoo" or "park" or "store" or "movies" or "kitchen" or "office"])
            return true;

        return words is ["and" or "in", "i" or "we" or "he" or "she" or "they",
            "don't" or "didn't" or "doesn't", "know", "why" or "how" or "what" or "where" or "when",
            "i" or "we" or "he" or "she" or "they" or "it",
            "hear" or "heard" or "had" or "saw" or "said" or "thought", .. var ending] &&
            // Accept ordinary sentence endings here. A second instruction can
            // otherwise be hidden after a valid conversational lead-in.
            ending is [] or
                ["some" or "something" or "anything" or "nothing" or "it" or "that" or "this" or "them"] or
                ["earlier" or "before" or "again" or "nearby"] or
                ["a" or "the" or "some", "sound" or "sounds" or "noise" or "voices" or "music"] or
                ["a" or "the" or "some", "sound" or "sounds" or "noise" or "voices" or "music",
                    "earlier" or "before" or "again" or "nearby"];
    }

    private static string NormalizeSpokenPhrase(string phrase) =>
        phrase.Replace("april fool's ", "april fools ", StringComparison.Ordinal)
            .Replace("april fool s ", "april fools ", StringComparison.Ordinal);

    internal static string? GetMimId(string intent) => ByIntent.GetValueOrDefault(intent)?.MimId;

    public static bool PreservesSpeechMarkup(string mimId) => ByMimId.ContainsKey(mimId);

    public static bool PreservesAnimation(string? mimId) =>
        mimId is not null && ByMimId.GetValueOrDefault(mimId)?.PreserveAnimation == true;

    public static bool PreservesPitch(string? mimId) =>
        mimId is not null && ByMimId.GetValueOrDefault(mimId)?.PreservePitch == true;
